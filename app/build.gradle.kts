// Kredensial privat dibaca dari local.properties (bukan gradle.properties),
// agar BuildConfig terisi benar saat build lewat CLI maupun Android Studio.
val localProps = Properties()
val localPropsFile = rootProject.file("local.properties")
if (localPropsFile.exists()) {
    localPropsFile.inputStream().use { localProps.load(it) }
}

fun secret(key: String): String =
    (project.findProperty(key) as? String)?.takeIf { it.isNotBlank() }
        ?: localProps.getProperty(key).orEmpty()

// Konfigurasi tanda tangan release (baca dari keystore.properties).
val keystoreProps = Properties()
val keystorePropsFile = rootProject.file("keystore.properties")
if (keystorePropsFile.exists()) {
    keystorePropsFile.inputStream().use { keystoreProps.load(it) }
}

